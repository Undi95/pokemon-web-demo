#!/usr/bin/env node
/**
 * extract-sine-table.mjs
 * ------------------------
 * Extrait `gSineTable` depuis `D:\Projet 1\decomps\pokeemeraude\src\trig.c`.
 *
 *   const s16 gSineTable[] = { Q_8_8(0), Q_8_8(0.0234375), ... };
 *   #define Q_8_8(n) ((s16)((n) * 256))
 *
 * Le commentaire indique que la table va de x=0 à x=319 (320 entrées),
 * pas 256 — c'est une astuce pour pouvoir indexer sin(i + 64) = cos(i)
 * sans wrap modulo. On préserve la longueur d'origine.
 *
 * Sortie : src/engine/decomp-data/auto/src/sine-table.ts
 *
 * Usage :  node scripts/extract-sine-table.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(__dirname, '..');
const decompRoot = resolve(projectRoot, '..', 'decomps', 'pokeemeraude');
const outDir = resolve(projectRoot, 'src', 'engine', 'decomp-data', 'auto', 'src');
const outFile = join(outDir, 'sine-table.ts');

mkdirSync(outDir, { recursive: true });

const trigSrc = readFileSync(join(decompRoot, 'src', 'trig.c'), 'utf8');

// Find `const s16 gSineTable[] = {`
const startMatch = trigSrc.match(/const\s+s16\s+gSineTable\s*\[\s*\]\s*=\s*\{/);
if (!startMatch) {
  console.error('[sine-table] Could not locate gSineTable[] = { in trig.c');
  process.exit(1);
}
const startIdx = startMatch.index + startMatch[0].length;

// Find matching closing `};`
let depth = 1;
let i = startIdx;
while (i < trigSrc.length && depth > 0) {
  if (trigSrc[i] === '{') depth++;
  else if (trigSrc[i] === '}') depth--;
  if (depth === 0) break;
  i++;
}
if (depth !== 0) {
  console.error('[sine-table] Unbalanced braces while parsing gSineTable');
  process.exit(1);
}
const body = trigSrc.slice(startIdx, i);

// Strip /* ... */ and // ... comments
const cleaned = body
  .replace(/\/\*[\s\S]*?\*\//g, ' ')
  .replace(/\/\/[^\n]*/g, ' ');

// Match every Q_8_8(<numeric>) entry — preserve order
const entryRe = /Q_8_8\s*\(\s*(-?\d+(?:\.\d+)?)\s*\)/g;
const values = [];
let m;
while ((m = entryRe.exec(cleaned)) !== null) {
  // GBA macro: Q_8_8(n) ((s16)((n) * 256))
  // Cast to s16 emulates wrap-around for negative results — but the source
  // values here are sin() ∈ [-1, 1], so n*256 ∈ [-256, 256] which always
  // fits in s16. Just round (the decomp values are already exact rationals).
  const n = parseFloat(m[1]);
  const q = Math.round(n * 256);
  values.push(q);
}

if (values.length === 0) {
  console.error('[sine-table] No Q_8_8(...) entries parsed');
  process.exit(1);
}

// Sanity: known values
const sanityChecks = [
  [0,   0],
  [64,  256],
  [128, 0],
  [192, -256],
];
let sanityOk = true;
for (const [idx, expected] of sanityChecks) {
  if (values[idx] !== expected) {
    console.warn(`[sine-table] Sanity FAIL gSineTable[${idx}]: got ${values[idx]}, expected ${expected}`);
    sanityOk = false;
  }
}

const NOW = new Date().toISOString().slice(0, 10);
const out = [
  `// AUTO-GENERATED by scripts/extract-sine-table.mjs`,
  `// Source: src/trig.c (decomp pokeemeraude)`,
  `// Generated: ${NOW}`,
  `//`,
  `// gSineTable[i] = round(sin(i * π / 128) * 256)  -- Q.8 fixed-point`,
  `// Length: ${values.length} entries (x=0..${values.length - 1}; >256 to allow gSineTable[i + 64] = cos)`,
  `// Sanity: gSineTable[0]=${values[0]}, [64]=${values[64]}, [128]=${values[128]}, [192]=${values[192]}`,
  ``,
  `export const G_SINE_TABLE: ReadonlyArray<number> = [`,
  ...chunkArray(values, 16).map(row => `  ${row.join(', ')},`),
  `];`,
  ``,
  `/** Convenience: cosine = sine shifted by 64 (π/2). */`,
  `export function gSineTable(idx: number): number {`,
  `  return G_SINE_TABLE[idx];`,
  `}`,
  ``,
].join('\n');

writeFileSync(outFile, out);

console.log(`[sine-table] Output: ${outFile.replace(/\\/g, '/')}`);
console.log(`[sine-table] Entries: ${values.length}`);
console.log(`[sine-table] First 8: ${values.slice(0, 8).join(', ')}`);
console.log(`[sine-table] Sanity: gSineTable[0]=${values[0]}, [64]=${values[64]}, [128]=${values[128]}, [192]=${values[192]}`);
console.log(`[sine-table] Sanity check: ${sanityOk ? 'OK' : 'FAIL'}`);

function chunkArray(arr, n) {
  const out = [];
  for (let i = 0; i < arr.length; i += n) out.push(arr.slice(i, i + n));
  return out;
}
