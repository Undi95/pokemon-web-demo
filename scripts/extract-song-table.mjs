#!/usr/bin/env node
/**
 * extract-song-table.mjs
 * ----------------------
 * Parse `decomp/include/constants/songs.h` pour extraire la table complète
 * songId → song name (= base filename .mid sans extension).
 *
 * Décomp pattern :
 *   #define MUS_INTRO       414 // mus_intro_battle ← commentaire utile mais pas
 *                                                    fiable, on déduit du nom du symbol
 *   #define SE_INTRO_BLAST  103 // SE_OP_BASYU      ← idem, on garde le nom du symbol
 *
 * Le nom du fichier .mid est `mus_<lowercase>` ou `se_<lowercase>` du symbol C.
 *   MUS_INTRO → mus_intro
 *   SE_INTRO_BLAST → se_intro_blast
 *   SE_M_THUNDERBOLT → se_m_thunderbolt
 *
 * Output : `src/engine/decomp-data/auto/src/song-table.ts` avec
 *          `export const SONG_ID_TO_NAME: Record<number, string>`.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(__dirname, '..');
const decompRoot = resolve(projectRoot, '..', 'decomps', 'pokeemeraude');
const songsHPath = resolve(decompRoot, 'include', 'constants', 'songs.h');
const midiCfgPath = resolve(decompRoot, 'sound', 'songs', 'midi', 'midi.cfg');
const outDir = resolve(projectRoot, 'src', 'engine', 'decomp-data', 'auto', 'src');
const outPath = resolve(outDir, 'song-table.ts');

const NOW = new Date().toISOString().slice(0, 10);

/** Parse `sound/songs/midi/midi.cfg` qui spécifie les options mid2agb par song.
 *  Format ligne : `<name>.mid: -E -Rxxx -G_voicegroup -Vxxx [-Pxxx]`
 *    -Rxxx : reverb level (0-127, 1:1 SOUND_MODE_REVERB_VAL)
 *    -Vxxx : volume master (0-255 ?? — souvent 080-127)
 *    -G_X  : voicegroup name (ex `_route101` → voicegroup_route101)
 *    -Pxxx : priority (rare)
 *  Si l'option manque, le défaut mid2agb s'applique (-1 = off pour reverb). */
function parseMidiCfg(path) {
  if (!existsSync(path)) return new Map();
  const src = readFileSync(path, 'utf8');
  const result = new Map(); // songName → { reverb, volume, voicegroup, priority }
  for (const line of src.split('\n')) {
    const m = /^(\w+)\.mid:\s+(.*)$/.exec(line.trim());
    if (!m) continue;
    const name = m[1];
    const args = m[2];
    const reverbM = /-R(\d+)/.exec(args);
    const volumeM = /-V(\d+)/.exec(args);
    const groupM = /-G_?(\w+)/.exec(args);
    const priorityM = /-P(\d+)/.exec(args);
    result.set(name, {
      reverb: reverbM ? parseInt(reverbM[1], 10) : null,
      volume: volumeM ? parseInt(volumeM[1], 10) : null,
      voicegroup: groupM ? groupM[1] : null,
      priority: priorityM ? parseInt(priorityM[1], 10) : null,
    });
  }
  return result;
}

function main() {
  const src = readFileSync(songsHPath, 'utf8');
  const midiCfg = parseMidiCfg(midiCfgPath);
  // Match `#define SYMBOL_NAME N` where SYMBOL is MUS_, SE_ ou starts with PH_
  const re = /^\s*#define\s+((?:MUS|SE|PH)_[A-Z0-9_]+)\s+(\d+)/gm;
  const entries = []; // { id: number, name: string }
  let m;
  while ((m = re.exec(src)) !== null) {
    const symbol = m[1];
    const id = parseInt(m[2], 10);
    if (!Number.isFinite(id)) continue;
    // Symbol → file name : lowercase the symbol.
    const name = symbol.toLowerCase();
    entries.push({ id, name, symbol });
  }

  // Dédup par id : songs.h contient plusieurs alias pour le même ID (ex MUS_DUMMY=0,
  // MUS_NONE=0, MUS_ROUTE118=0). On garde le 1er rencontré (= ordre de déclaration).
  const seenIds = new Set();
  const dedupEntries = [];
  for (const e of entries) {
    if (seenIds.has(e.id)) continue;
    seenIds.add(e.id);
    dedupEntries.push(e);
  }
  // Sort by id for stable output.
  dedupEntries.sort((a, b) => a.id - b.id);
  // Remplace l'array : le code suivant continue d'utiliser `entries`.
  entries.length = 0;
  entries.push(...dedupEntries);

  const lines = [];
  lines.push(`// AUTO-GENERATED by scripts/extract-song-table.mjs`);
  lines.push(`// Source : decomp/include/constants/songs.h`);
  lines.push(`// Generated : ${NOW}`);
  lines.push(`// DO NOT EDIT — re-run the script to refresh.`);
  lines.push(``);
  lines.push(`/* eslint-disable */`);
  lines.push(`/**`);
  lines.push(` * 1:1 décomp songId → song name mapping (MUS_* + SE_* + PH_*).`);
  lines.push(` * songName = lowercase du symbole C → nom du fichier .mid (sans extension).`);
  lines.push(` * Total : ${entries.length} songs.`);
  lines.push(` */`);
  lines.push(`export const SONG_ID_TO_NAME: Record<number, string> = {`);
  for (const e of entries) {
    lines.push(`  ${e.id}: '${e.name}',  // ${e.symbol}`);
  }
  lines.push(`};`);
  lines.push(``);
  lines.push(`/** Inverse : symbol C name → numeric ID. */`);
  lines.push(`export const SONG_NAME_TO_ID: Record<string, number> = {`);
  for (const e of entries) {
    lines.push(`  ${e.symbol}: ${e.id},`);
  }
  lines.push(`};`);
  lines.push(``);

  // ─── Per-song M4A config (reverb + master volume) depuis midi.cfg ─────────
  // 1:1 décomp `tools/mid2agb` arguments. Si pas de config pour un song, le
  // default mid2agb s'applique (reverb=-1 = off, volume=127 = full).
  lines.push(`/** Per-song M4A config 1:1 décomp \`sound/songs/midi/midi.cfg\` (mid2agb args).`);
  lines.push(` * - reverb : 0-127 ou null (off, mid2agb default)`);
  lines.push(` * - volume : master vol 0-127, ou null pour default`);
  lines.push(` * - voicegroup : nom du voicegroup (sans préfixe \`voicegroup_\`)`);
  lines.push(` * - priority : track priority si défini`);
  lines.push(` */`);
  lines.push(`export interface SongConfig {`);
  lines.push(`  reverb: number | null;`);
  lines.push(`  volume: number | null;`);
  lines.push(`  voicegroup: string | null;`);
  lines.push(`  priority: number | null;`);
  lines.push(`}`);
  lines.push(``);
  lines.push(`export const SONG_NAME_TO_CONFIG: Record<string, SongConfig> = {`);
  const cfgKeys = [...midiCfg.keys()].sort();
  for (const key of cfgKeys) {
    const c = midiCfg.get(key);
    lines.push(`  ${JSON.stringify(key)}: { reverb: ${c.reverb ?? 'null'}, volume: ${c.volume ?? 'null'}, voicegroup: ${c.voicegroup ? JSON.stringify(c.voicegroup) : 'null'}, priority: ${c.priority ?? 'null'} },`);
  }
  lines.push(`};`);
  lines.push(``);
  lines.push(`/** Helper : récupère la config M4A pour un song name (ou null). */`);
  lines.push(`export function getSongConfig(name: string): SongConfig | null {`);
  lines.push(`  return SONG_NAME_TO_CONFIG[name] ?? null;`);
  lines.push(`}`);
  lines.push(``);

  if (!existsSync(outDir)) mkdirSync(outDir, { recursive: true });
  writeFileSync(outPath, lines.join('\n'), 'utf8');
  console.log(`[extract-song-table] wrote ${outPath} (${entries.length} entries)`);
}

main();
