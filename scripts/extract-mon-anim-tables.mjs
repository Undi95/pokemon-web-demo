#!/usr/bin/env node
/**
 * extract-mon-anim-tables.mjs
 * ─────────────────────────────
 * Extract per-species front-pic animation mappings from pokeemeraude décomp.
 *
 * Input  : `src/pokemon.c` from local decomp checkout
 * Output : `src/engine/decomp-data/auto/src/mon-anim-tables-data.ts`
 *
 * Tables extracted :
 *   - sMonFrontAnimIdsTable[NUM_SPECIES - 1]      → species → ANIM_*
 *   - sMonAnimationDelayTable[NUM_SPECIES - 1]    → species → delay frames (0-N)
 *   - sMonHasTwoFramesAnimationTable[NUM_SPECIES] → species → bool (= has anim_front 2-frame strip)
 *
 * Usage :
 *   node scripts/extract-mon-anim-tables.mjs [DECOMP_ROOT]
 *
 * Default DECOMP_ROOT = D:/Projet 1/decomps/pokeemeraude
 *
 * Re-run if décomp updates (= pull pret pokeemerald + species changes).
 *
 * Foundation : output consumed par `src/engine/pokemon-anim-funcs.ts`
 *   - getMonFrontAnimId(species) → anim id pour DoMonFrontSpriteAnimation
 *   - getMonAnimDelay(species)   → delay avant idle anim launch
 *   - hasTwoFramesAnimation(species) → si oui, StartSpriteAnim(sprite, 1)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// ─── Args parse ─────────────────────────────────────────────────────────────
const args = process.argv.slice(2);
const DECOMP_ROOT = args[0] || 'D:/Projet 1/decomps/pokeemeraude';
const POKEMON_C = path.join(DECOMP_ROOT, 'src', 'pokemon.c');
const OUT_PATH = path.join(__dirname, '..', 'src', 'engine', 'decomp-data', 'auto', 'src', 'mon-anim-tables-data.ts');

if (!fs.existsSync(POKEMON_C)) {
  console.error(`[extract-mon-anim-tables] pokemon.c not found at: ${POKEMON_C}`);
  console.error(`Pass DECOMP_ROOT as 1st arg if your checkout is elsewhere.`);
  process.exit(1);
}

const src = fs.readFileSync(POKEMON_C, 'utf8');

// ─── Helpers : parse C designated initializer arrays ────────────────────────
//
// Find  : `const TYPE NAME[SIZE_EXPR] = { [INDEX_EXPR] = VALUE, ... };`
// Capture array body, parse entries.

function findArrayBody(arrayName) {
  // Match `const ... arrayName[...] = { ... };`
  // Greedy {...} — assume balanced braces, take everything up to next `};` at line start.
  const re = new RegExp(
    `\\b${arrayName}\\b[^=]*=\\s*\\{([\\s\\S]*?)\\}\\s*;`,
    'm',
  );
  const m = src.match(re);
  if (!m) return null;
  return m[1];
}

function parseDesignatedInits(body) {
  // Match `[KEY_EXPR] = VALUE,` — KEY_EXPR can be `SPECIES_X` or `SPECIES_X - 1` etc.
  // VALUE is identifier or number until comma/end.
  const entries = [];
  // Strip C comments (single-line + multi-line)
  const cleaned = body
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/\/\/[^\n]*/g, '');
  const re = /\[\s*([^\]]+?)\s*\]\s*=\s*([^,}]+)\s*,?/g;
  let m;
  while ((m = re.exec(cleaned)) !== null) {
    const key = m[1].trim();
    const value = m[2].trim();
    entries.push({ key, value });
  }
  return entries;
}

/** From `SPECIES_X - 1` extract `SPECIES_X`. From `SPECIES_X` return as-is. */
function normalizeSpeciesKey(rawKey) {
  // Strip trailing arithmetic `- 1` etc.
  const m = rawKey.match(/^(SPECIES_\w+)/);
  return m ? m[1] : rawKey;
}

// ─── Extract arrays ─────────────────────────────────────────────────────────
console.log(`[extract-mon-anim-tables] reading: ${POKEMON_C}`);

const animIdsBody = findArrayBody('sMonFrontAnimIdsTable');
const delayBody = findArrayBody('sMonAnimationDelayTable');
const hasTwoFramesBody = findArrayBody('sMonHasTwoFramesAnimationTable');

const animIdsEntries = animIdsBody ? parseDesignatedInits(animIdsBody) : [];
const delayEntries = delayBody ? parseDesignatedInits(delayBody) : [];
const hasTwoFramesEntries = hasTwoFramesBody ? parseDesignatedInits(hasTwoFramesBody) : [];

console.log(`  sMonFrontAnimIdsTable    : ${animIdsEntries.length} entries`);
console.log(`  sMonAnimationDelayTable  : ${delayEntries.length} entries`);
console.log(`  sMonHasTwoFramesAnimTable: ${hasTwoFramesEntries.length} entries`);

if (animIdsEntries.length === 0) {
  console.error(`[extract-mon-anim-tables] sMonFrontAnimIdsTable not found or empty.`);
  console.error(`Check that pokemon.c contains the array declaration.`);
  process.exit(1);
}

// ─── Generate TS output ─────────────────────────────────────────────────────
//
// Format : pure data file with Map literals. Importable by pokemon-anim-funcs.
// Uses string keys (= SPECIES_X, ANIM_Y identifiers) and resolves at TS compile
// time via imports from species-data + pokemon-anim-funcs constants.

const lines = [];
lines.push('// AUTO-GENERATED by scripts/extract-mon-anim-tables.mjs');
lines.push(`// Source : ${POKEMON_C.replace(/\\/g, '/')}`);
lines.push(`// Generated : ${new Date().toISOString()}`);
lines.push('//');
lines.push('// Re-run le script si pokemon.c update dans la décomp.');
lines.push('// Modifications manuelles seront écrasées au prochain run.');
lines.push('');
lines.push('// Format : 3 Maps lookups species_id (1-based, = SPECIES_X numerical)');
lines.push('// → animation metadata. Indexed par species id directement.');
lines.push('');

// Helper : emit Map<species_string, value_string> literal
function emitMap(name, entries, valueTransform = (v) => `'${v}'`) {
  const lines = [];
  lines.push(`export const ${name}: ReadonlyArray<readonly [string, string]> = [`);
  for (const e of entries) {
    const speciesName = normalizeSpeciesKey(e.key);
    lines.push(`  ['${speciesName}', '${e.value}'],`);
  }
  lines.push(`];`);
  return lines.join('\n');
}

lines.push('/** Raw species → ANIM_* mapping extracted from sMonFrontAnimIdsTable.');
lines.push(' *  String form (= SPECIES_X / ANIM_Y identifiers) ; resolved au run-time');
lines.push(' *  via imports dans pokemon-anim-funcs.ts. */');
lines.push(emitMap('RAW_MON_FRONT_ANIM_IDS', animIdsEntries));
lines.push('');

lines.push('/** Raw species → delay frames mapping. */');
lines.push(emitMap('RAW_MON_ANIM_DELAYS', delayEntries));
lines.push('');

lines.push('/** Raw species → boolean (= has 2-frame anim_front sheet). */');
lines.push(emitMap('RAW_MON_HAS_TWO_FRAMES', hasTwoFramesEntries));
lines.push('');

const out = lines.join('\n') + '\n';
fs.mkdirSync(path.dirname(OUT_PATH), { recursive: true });
fs.writeFileSync(OUT_PATH, out, 'utf8');

console.log(`[extract-mon-anim-tables] wrote: ${OUT_PATH}`);
console.log(`  ${animIdsEntries.length + delayEntries.length + hasTwoFramesEntries.length} total entries`);
