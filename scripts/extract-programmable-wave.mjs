#!/usr/bin/env node
/**
 * extract-programmable-wave.mjs
 * -----------------------------
 * Extrait les programmable wave samples GBA depuis le décomp.
 *
 * Source : `sound/programmable_wave_samples/NN.pcm` — 16 octets = 32 nibbles 4-bit.
 *           Chaque nibble (0-15) est un sample d'amplitude de la wave shape.
 *           1:1 hardware GB Sound Channel 3 (cf. GBATEK).
 *
 * Output : `src/engine/decomp-data/auto/src/programmable-waves.ts`
 *           Map ProgrammableWaveData_N → Float32Array(32) des samples normalisés ±1.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(__dirname, '..');
const decompRoot = resolve(projectRoot, '..', 'decomps', 'pokeemeraude');
const sampleDir = resolve(decompRoot, 'sound', 'programmable_wave_samples');
const outDir = resolve(projectRoot, 'src', 'engine', 'decomp-data', 'auto', 'src');
const outPath = resolve(outDir, 'programmable-waves.ts');

const NOW = new Date().toISOString().slice(0, 10);

function pcmToSamples(buf) {
  // 16 octets → 32 nibbles 4-bit, chacun mappé en ±1.
  // 1:1 hardware GB : nibble est 4-bit signed-ish, centré autour de 7.5
  // (= moyenne 0 quand interprété comme PCM AC).
  const samples = new Float32Array(32);
  for (let i = 0; i < 16; i++) {
    const high = (buf[i] >> 4) & 0xF;
    const low = buf[i] & 0xF;
    samples[i * 2] = (high - 7.5) / 7.5;       // ∈ [-1, +1]
    samples[i * 2 + 1] = (low - 7.5) / 7.5;
  }
  return samples;
}

function main() {
  if (!existsSync(sampleDir)) {
    console.warn(`[extract-pwv] sample dir not found: ${sampleDir}`);
    return;
  }
  const files = readdirSync(sampleDir).filter(f => f.endsWith('.pcm')).sort();
  const entries = [];  // { symbol, samples }
  for (const f of files) {
    const buf = readFileSync(resolve(sampleDir, f));
    if (buf.length !== 16) {
      console.warn(`[extract-pwv] unexpected size ${buf.length} for ${f}, skip`);
      continue;
    }
    const num = parseInt(f.slice(0, 2), 10);
    const symbol = `ProgrammableWaveData_${num}`;
    entries.push({ symbol, samples: pcmToSamples(buf) });
  }

  const lines = [];
  lines.push(`// AUTO-GENERATED by scripts/extract-programmable-wave.mjs`);
  lines.push(`// Source : decomp/sound/programmable_wave_samples/NN.pcm (16 octets = 32 nibbles 4-bit)`);
  lines.push(`// Generated : ${NOW}`);
  lines.push(`// DO NOT EDIT — re-run the script to refresh.`);
  lines.push(``);
  lines.push(`/* eslint-disable */`);
  lines.push(`/**`);
  lines.push(` * Programmable wave samples GBA (channel 3) — 1:1 décomp.`);
  lines.push(` * Chaque entry = Float32Array(32) avec samples normalisés ±1.`);
  lines.push(` */`);
  lines.push(`export const PROGRAMMABLE_WAVES: Record<string, Float32Array> = {`);
  for (const e of entries) {
    const arr = [...e.samples].map(v => v.toFixed(6)).join(', ');
    lines.push(`  ${e.symbol}: new Float32Array([${arr}]),`);
  }
  lines.push(`};`);
  lines.push(``);

  if (!existsSync(outDir)) mkdirSync(outDir, { recursive: true });
  writeFileSync(outPath, lines.join('\n'), 'utf8');
  console.log(`[extract-pwv] wrote ${outPath} (${entries.length} waves)`);
}

main();
