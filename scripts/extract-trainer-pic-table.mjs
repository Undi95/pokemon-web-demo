#!/usr/bin/env node
/**
 * extract-trainer-pic-table.mjs
 * ──────────────────────────────
 * Extract trainer front pic registry from pokeemeraude décomp.
 *
 * Input  : `src/data/trainer_graphics/front_pic_tables.h` from local checkout
 * Output : `src/engine/decomp-data/auto/src/trainer-pic-tables-data.ts`
 *
 * Tables extracted :
 *   - gTrainerFrontPicTable[]         → trainerPicId → gfx symbol
 *   - gTrainerFrontPicPaletteTable[]  → trainerPicId → palette symbol
 *
 * Usage :
 *   node scripts/extract-trainer-pic-table.mjs [DECOMP_ROOT]
 *
 * Default DECOMP_ROOT = D:/Projet 1/decomps/pokeemeraude
 *
 * Foundation : output consumed par futur `src/engine/trainer-pic-graphics.ts`
 *   - GetTrainerFrontPicInfo(picId) → { gfxSymbol, palSymbol }
 *   - CreateTrainerSpriteFromIndex(picId, x, y, ...) → spriteId
 *
 * Phase 4 (battle scenes) utilisera ces helpers pour spawn dynamiquement
 * les trainer back-pics (= protagoniste) + front-pics (= adversaire).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const args = process.argv.slice(2);
const DECOMP_ROOT = args[0] || 'D:/Projet 1/decomps/pokeemeraude';
const FRONT_PIC_TABLES = path.join(DECOMP_ROOT, 'src', 'data', 'trainer_graphics', 'front_pic_tables.h');
const OUT_PATH = path.join(__dirname, '..', 'src', 'engine', 'decomp-data', 'auto', 'src', 'trainer-pic-tables-data.ts');

if (!fs.existsSync(FRONT_PIC_TABLES)) {
  console.error(`[extract-trainer-pic-table] file not found: ${FRONT_PIC_TABLES}`);
  console.error(`Pass DECOMP_ROOT as 1st arg if checkout is elsewhere.`);
  process.exit(1);
}

const src = fs.readFileSync(FRONT_PIC_TABLES, 'utf8');

// ─── Parse C designated initializer arrays (= same pattern as mon-anim) ────

function findArrayBody(arrayName) {
  const re = new RegExp(
    `\\b${arrayName}\\b[^=]*=\\s*\\{([\\s\\S]*?)\\}\\s*;`,
    'm',
  );
  const m = src.match(re);
  return m ? m[1] : null;
}

/** Parse `[TRAINER_PIC_X] = TRAINER_SPRITE(NAME, SIZE, GFX_SYMBOL)` style entries.
 *  Decomp uses helper macros : `TRAINER_SPRITE(short, size, gfx)` and
 *  `TRAINER_PAL(short, pal)`. We capture the raw arg list and extract names. */
function parseTrainerEntries(body) {
  const cleaned = body
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/\/\/[^\n]*/g, '');
  // Match each `[KEY] = ANY_VALUE,` where ANY_VALUE may contain parens.
  // Use bracket-balance manual scan.
  const entries = [];
  let i = 0;
  while (i < cleaned.length) {
    const lbIdx = cleaned.indexOf('[', i);
    if (lbIdx < 0) break;
    const rbIdx = cleaned.indexOf(']', lbIdx);
    if (rbIdx < 0) break;
    const eqIdx = cleaned.indexOf('=', rbIdx);
    if (eqIdx < 0) break;
    const key = cleaned.slice(lbIdx + 1, rbIdx).trim();
    // Read value until next `,` at depth 0 (= top-level of array body).
    let depth = 0;
    let j = eqIdx + 1;
    while (j < cleaned.length) {
      const ch = cleaned[j];
      if (ch === '(' || ch === '{') depth++;
      else if (ch === ')' || ch === '}') depth--;
      else if (ch === ',' && depth === 0) break;
      j++;
    }
    const value = cleaned.slice(eqIdx + 1, j).trim();
    entries.push({ key, value });
    i = j + 1;
  }
  return entries;
}

/** Extract gfx symbol from value. Decomp pattern :
 *   TRAINER_SPRITE(NAME, SIZE, gTrainerFrontPic_X)
 *   TRAINER_PAL(NAME, gTrainerPalette_X)
 *   { gTrainerFrontPic_X, SIZE, TRAINER_PIC_X }   (= legacy)
 *  We capture the gTrainerFrontPic_X / gTrainerPalette_X identifier. */
function extractSymbol(value) {
  // Look for gTrainerFrontPic_X or gTrainerPalette_X
  const m = value.match(/g(?:TrainerFrontPic|TrainerPalette)_\w+/);
  return m ? m[0] : null;
}

const frontPicBody = findArrayBody('gTrainerFrontPicTable');
const frontPalBody = findArrayBody('gTrainerFrontPicPaletteTable');

const frontPicEntries = frontPicBody ? parseTrainerEntries(frontPicBody) : [];
const frontPalEntries = frontPalBody ? parseTrainerEntries(frontPalBody) : [];

console.log(`[extract-trainer-pic-table] reading: ${FRONT_PIC_TABLES}`);
console.log(`  gTrainerFrontPicTable        : ${frontPicEntries.length} entries`);
console.log(`  gTrainerFrontPicPaletteTable : ${frontPalEntries.length} entries`);

if (frontPicEntries.length === 0) {
  console.error(`[extract-trainer-pic-table] gTrainerFrontPicTable not found.`);
  process.exit(1);
}

// ─── Generate TS output ─────────────────────────────────────────────────────

const lines = [];
lines.push('// AUTO-GENERATED by scripts/extract-trainer-pic-table.mjs');
lines.push(`// Source : ${FRONT_PIC_TABLES.replace(/\\/g, '/')}`);
lines.push(`// Generated : ${new Date().toISOString()}`);
lines.push('//');
lines.push('// Re-run le script si front_pic_tables.h update dans la décomp.');
lines.push('// Modifications manuelles seront écrasées au prochain run.');
lines.push('');
lines.push('/** Raw trainer pic id → gfx symbol identifier. String form ; resolved');
lines.push(' *  au run-time via le framework consumer trainer-pic-graphics.ts. */');
lines.push('export const RAW_TRAINER_FRONT_PIC_GFX: ReadonlyArray<readonly [string, string]> = [');
for (const e of frontPicEntries) {
  const symbol = extractSymbol(e.value);
  if (symbol) lines.push(`  ['${e.key}', '${symbol}'],`);
}
lines.push(`];`);
lines.push('');
lines.push('/** Raw trainer pic id → palette symbol identifier. */');
lines.push('export const RAW_TRAINER_FRONT_PIC_PAL: ReadonlyArray<readonly [string, string]> = [');
for (const e of frontPalEntries) {
  const symbol = extractSymbol(e.value);
  if (symbol) lines.push(`  ['${e.key}', '${symbol}'],`);
}
lines.push(`];`);
lines.push('');

const out = lines.join('\n');
fs.mkdirSync(path.dirname(OUT_PATH), { recursive: true });
fs.writeFileSync(OUT_PATH, out, 'utf8');

console.log(`[extract-trainer-pic-table] wrote: ${OUT_PATH}`);
