#!/usr/bin/env node
/**
 * gen-all-auto-barrel.mjs
 * -----------------------
 * Génère `src/engine/decomp-data/auto/src-all/_barrel.ts` qui re-export
 * TOUS les `*-all-auto.ts` à plat. Utilisé par option-menu-impl pour
 * expose tous les exports sur globalThis (= 1:1 décomp scope C où tous
 * les symboles globaux sont visibles cross-fichier).
 *
 * Stratégie pour gérer les conflicts de noms (= MainCB2/VBlankCB définis
 * dans plusieurs fichiers) : `export *` ne marche pas (silently résout
 * vers le dernier seen). On utilise des namespaces (= `export * as fooAuto
 * from './foo-all-auto'`) qui exposent fooAuto.X. Le consumer (option-menu-impl)
 * peut alors itérer Object.entries de chaque namespace + dedupe.
 */
import fs from 'node:fs';
import path from 'node:path';

const DIR = path.resolve('src/engine/decomp-data/auto/src-all');
const OUT = path.resolve(DIR, '_barrel.ts');

// Note : les transpiler bugs syntactic sont normalement fixés par
// scripts/post-transpile-patches.mjs (= patchAllAutoSyntaxBugs).
// On inclut TOUS les fichiers ; si un fichier a encore un bug syntactic,
// vite throwra à l'import et on devra ajouter un patch supplémentaire.
const files = fs.readdirSync(DIR)
  .filter(f => f.endsWith('-all-auto.ts') && !f.startsWith('_'))
  .sort();

const lines = [
  '// AUTO-GENERATED by scripts/gen-all-auto-barrel.mjs',
  '// Re-export tous les *-all-auto.ts via namespaces.',
  `// Total : ${files.length} files.`,
  '',
];

for (const f of files) {
  const stem = f.replace(/-all-auto\.ts$/, '');
  // Namespace name : sanitize + camelCase. e.g. "battle_anim" → "battleAnim".
  const ns = stem
    .split(/[_-]/)
    .map((p, i) => i === 0 ? p.toLowerCase() : p[0].toUpperCase() + p.slice(1).toLowerCase())
    .join('')
    .replace(/[^A-Za-z0-9_$]/g, '');
  const nsAuto = ns + 'Auto';
  lines.push(`export * as ${nsAuto} from './${stem}-all-auto';`);
}

fs.writeFileSync(OUT, lines.join('\n') + '\n', 'utf8');
console.log(`[gen-all-auto-barrel] wrote ${OUT}`);
console.log(`[gen-all-auto-barrel] ${files.length} namespaces exported`);
