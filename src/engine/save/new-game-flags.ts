/** Initialise les flags d'une nouvelle partie. À call au boot très early. */
export function NewGameInit(): void {
  // 1:1 décomp `NewGameInitData` (new_game.c:171) : ClearBerryTrees() — reset les
  // 128 berry trees à gBlankBerryTree AVANT le planting initial.
  ClearBerryTrees();
  for (const flagId of NEW_GAME_HIDE_FLAGS) {
    FlagSet(flagId);
  }
  // 1:1 décomp : EventScript_ResetAllMapFlags finit par `call EventScript_ResetAllBerries`
  // (new_game.inc:275) — plante les ~80 baies fixes initiales (Routes 102/104/116/…) au
  // stade BERRY_STAGE_BERRIES (récoltable, figées via allowGrowth=FALSE).
  ResetAllBerries();
  // 1:1 décomp `InitPlayerTrainerId()` (new_game.c:84) appelé depuis
  // `NewGameInitData()` (= line 164). Build un u32 trainerId :
  //   trainerId = (Random() << 16) | GetGeneratedTrainerIdLower()
  // Sans ça, playerTrainerId reste à 0 → tous les NPCs/Pokémon "ours" ont le
  // même trainer ID = 0, breaks les checks Pokemon flags (= "trade vs caught").
  // SYNC (pas async) car gameState.save() peut être appelé immédiatement
  // après NewGameInit (= boot-mode.ts ?truck preset → reset+NewGameInit+save)
  // → trainerId doit être persisté dans la save SaveBlock2.
  const trainerId = ((Random() << 16) | GetGeneratedTrainerIdLower()) >>> 0;
  gSaveBlock2Ptr.playerTrainerId = trainerId >>> 0;
  // 1:1 décomp `NewGameInitData` (new_game.c:172) :
  //   SetMoney(&gSaveBlock1Ptr->money, 3000);
  // ⇒ argent de départ standard du jeu (= 3000$ pour acheter PokéBalls/Potions
  // à Oldale Town / Petalburg Mart). Sans ça, le joueur boot à 0$.
  SetMoney(3000);
  // 1:1 décomp `NewGameInitData` (new_game.c:186-187) :
  //   ClearBag();
  //   NewGameInitPCItems();
  // ⇒ ajoute 1× POTION dans le PC du joueur. Sans ça, le PC est vide au boot
  // alors que le décomp officiel donne toujours 1 POTION en stockage.
  void import('../pokemon/pc-items').then(({ NewGameInitPCItems }) => {
    NewGameInitPCItems();
  });
  console.log(`[new-game-flags] InitPlayerTrainerId : trainerId=0x${trainerId.toString(16).padStart(8, '0')}`);
  console.log(`[new-game-flags] set ${NEW_GAME_HIDE_FLAGS.length} hide flags (= EventScript_ResetAllMapFlags)`);
}
